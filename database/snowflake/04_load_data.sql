-- =====================================================================
-- TransitPulse - loading data into Snowflake
--
-- Step 1 (SnowSQL, from the project root) - upload the files:
--
--   snowsql -a <account> -u <user> -r <role> \
--           -w TRANSITPULSE_WH -d TRANSITPULSE -s RAW
--
--   PUT file://datasets/*.csv                  @TRANSITPULSE_STAGE/datasets/
--       AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
--   PUT file://data-engine/output/csv/*.csv     @TRANSITPULSE_STAGE/engine/
--       AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
--
-- Step 2 - run this script. Credentials never appear in SQL.
-- =====================================================================
USE DATABASE TRANSITPULSE;
USE SCHEMA RAW;

LIST @TRANSITPULSE_STAGE;

-- ---------------- source datasets ----------------
COPY INTO RAW_ROUTES
  FROM @TRANSITPULSE_STAGE/datasets/routes.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_STOPS
  FROM @TRANSITPULSE_STAGE/datasets/stops.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_ROUTE_STOPS
  FROM @TRANSITPULSE_STAGE/datasets/route_stops.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_VEHICLES
  FROM @TRANSITPULSE_STAGE/datasets/vehicles.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_TRIPS
  FROM @TRANSITPULSE_STAGE/datasets/trips.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_SCHEDULED_MOVEMENTS
  FROM @TRANSITPULSE_STAGE/datasets/scheduled_movements.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_ACTUAL_MOVEMENTS
  FROM @TRANSITPULSE_STAGE/datasets/actual_movements.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_PASSENGER_VOLUMES
  FROM @TRANSITPULSE_STAGE/datasets/passenger_volumes.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_CONNECTIONS
  FROM @TRANSITPULSE_STAGE/datasets/connections.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_INCIDENTS
  FROM @TRANSITPULSE_STAGE/datasets/incidents.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_DIVERSIONS
  FROM @TRANSITPULSE_STAGE/datasets/diversions.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

-- ---------------- engine output ----------------
COPY INTO RAW_DELAY_EVENTS
  FROM @TRANSITPULSE_STAGE/engine/delay_events.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_PROPAGATION_RESULTS
  FROM @TRANSITPULSE_STAGE/engine/propagation_results.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_CONNECTION_RISK
  FROM @TRANSITPULSE_STAGE/engine/connection_risk.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_PASSENGER_IMPACT
  FROM @TRANSITPULSE_STAGE/engine/passenger_impact.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_SENSITIVITY_ANALYSIS
  FROM @TRANSITPULSE_STAGE/engine/sensitivity_analysis.csv.gz
  FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
  ON_ERROR = 'ABORT_STATEMENT';

-- ---------------- verify the load ----------------
SELECT 'RAW_ROUTES' AS table_name, COUNT(*) AS row_count FROM RAW_ROUTES
UNION ALL SELECT 'RAW_STOPS',               COUNT(*) FROM RAW_STOPS
UNION ALL SELECT 'RAW_TRIPS',               COUNT(*) FROM RAW_TRIPS
UNION ALL SELECT 'RAW_SCHEDULED_MOVEMENTS', COUNT(*) FROM RAW_SCHEDULED_MOVEMENTS
UNION ALL SELECT 'RAW_ACTUAL_MOVEMENTS',    COUNT(*) FROM RAW_ACTUAL_MOVEMENTS
UNION ALL SELECT 'RAW_PASSENGER_VOLUMES',   COUNT(*) FROM RAW_PASSENGER_VOLUMES
UNION ALL SELECT 'RAW_CONNECTIONS',         COUNT(*) FROM RAW_CONNECTIONS
UNION ALL SELECT 'RAW_INCIDENTS',           COUNT(*) FROM RAW_INCIDENTS
UNION ALL SELECT 'RAW_DELAY_EVENTS',        COUNT(*) FROM RAW_DELAY_EVENTS
UNION ALL SELECT 'RAW_PROPAGATION_RESULTS', COUNT(*) FROM RAW_PROPAGATION_RESULTS
UNION ALL SELECT 'RAW_CONNECTION_RISK',     COUNT(*) FROM RAW_CONNECTION_RISK
UNION ALL SELECT 'RAW_PASSENGER_IMPACT',    COUNT(*) FROM RAW_PASSENGER_IMPACT
UNION ALL SELECT 'RAW_SENSITIVITY_ANALYSIS', COUNT(*) FROM RAW_SENSITIVITY_ANALYSIS
ORDER BY table_name;

